"""
Board of Realities - NPC free-text interaction backend.

A tiny FastAPI service that lets the player type free text at an NPC and
get back a live, in-character reply generated by an LLM, instead of a
canned/keyword-matched response. For the Capital Syndicate roster (finance
titans, crime syndicate, presidents, Fed/FTC chairmen, agency heads - ~90
characters) the reply also carries a persuasion verdict: whether THIS
specific character, given their real personality/biography data, would
actually agree to what the player asked, plus how the exchange shifted
their opinion of the player.

Run with (from the project root):
    uvicorn backend.main:app --reload --port 8091

The frontend (Vite dev server on http://localhost:5173) calls this via
src/utils/npcChatClient.js -> POST http://localhost:8091/npc-interact

(Port 8091, not the more obvious 8000 - 8000 is already occupied on dev
machines that run other local FastAPI services alongside this repo. Also not
8079, this project's original port - abandoned after a dev-machine-specific
orphaned socket on 8079 wouldn't release even under a forceful process kill.)

The OpenAI API key is read from the project's root `.env` (OPENAI_API_KEY)
and never leaves this process - the browser never sees it.

Model/endpoint note: this project's OpenAI key only has access to
`gpt-5.6-luna` via the /v1/responses endpoint (verified directly against
the API - gpt-4o-mini and every /v1/chat/completions call 403 on this
project's model allowlist). If the key is later swapped for one with
broader access, MODEL below is the only thing that needs to change.
"""

