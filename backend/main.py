class GuideAskRequest(BaseModel):
    question: str = Field(..., min_length=1, max_length=500)


class GuideAskResponse(BaseModel):
    reply: str


@app.post("/guide-ask", response_model=GuideAskResponse)
def guide_ask(req: GuideAskRequest):
    if _client is None:
        raise HTTPException(
            status_code=500,
            detail="OPENAI_API_KEY is not configured on the backend (.env at project root).",
        )

    try:
        resp = _client.responses.create(
            model=MODEL,
            input=[
                {"role": "system", "content": GUIDE_SYSTEM_PROMPT},
                {"role": "user", "content": req.question},
            ],
            reasoning={"effort": "none"},
            max_output_tokens=220,
        )
        text = (resp.output_text or "").strip()
    except Exception as exc:  # noqa: BLE001 - surface any OpenAI/client error uniformly
        raise HTTPException(status_code=502, detail=f"OpenAI request failed: {exc}") from exc

    if not text:
        raise HTTPException(status_code=502, detail="OpenAI returned an empty reply.")

    return GuideAskResponse(reply=text[:700])


# ---------------------------------------------------------------------------
# Request / response schema
# ---------------------------------------------------------------------------

class ConversationTurn(BaseModel):
    role: str  # "player" | "npc"
    text: str


class NpcInteractRequest(BaseModel):
    npcId: str
    playerText: str = Field(..., min_length=1, max_length=1000)
    relationshipTier: float = 0
    conversationHistory: list[ConversationTurn] = []
    # Roster + biography data for the Capital Syndicate cast (finance/crime/
    # government/agency), built by the frontend from characterLookup.js +
    # characterBiographies.js. Omitted by worlds that still use the static
    # NPC_PERSONAS above (Hunter's Rift, King of Games).
    character: Optional[dict[str, Any]] = None


class NpcInteractResponse(BaseModel):
    reply: str
    agreed: bool = False
    relationshipDelta: int = 0


RESPONSE_SCHEMA = {
    "type": "json_schema",
    "name": "npc_reply",
    "schema": {
        "type": "object",
        "properties": {
            "reply": {"type": "string"},
            "agreed": {"type": "boolean"},
            "relationshipDelta": {"type": "integer"},
        },
        "required": ["reply", "agreed", "relationshipDelta"],
        "additionalProperties": False,
    },
    "strict": True,
}


@app.get("/health")
def health():
    return {"status": "ok", "hasApiKey": bool(OPENAI_API_KEY), "model": MODEL}


@app.post("/npc-interact", response_model=NpcInteractResponse)
def npc_interact(req: NpcInteractRequest):
    if _client is None:
        raise HTTPException(
            status_code=500,
            detail="OPENAI_API_KEY is not configured on the backend (.env at project root).",
        )

    system_prompt = build_system_prompt(req.npcId, req.relationshipTier, req.character)

    messages = [{"role": "system", "content": system_prompt}]
    # Keep only the last few turns of history to bound token usage.
    for turn in req.conversationHistory[-10:]:
        role = "assistant" if turn.role == "npc" else "user"
        messages.append({"role": role, "content": turn.text})
    messages.append({"role": "user", "content": req.playerText})

    try:
        resp = _client.responses.create(
            model=MODEL,
            input=messages,
            reasoning={"effort": "none"},
            max_output_tokens=600,
            text={"format": RESPONSE_SCHEMA},
        )
        parsed = json.loads(resp.output_text)
    except Exception as exc:  # noqa: BLE001 - surface any OpenAI/client/parse error uniformly
        raise HTTPException(status_code=502, detail=f"OpenAI request failed: {exc}") from exc

    delta = int(parsed.get("relationshipDelta", 0) or 0)
    delta = max(-3, min(3, delta))
    reply = (parsed.get("reply") or "").strip() or "..."

    return NpcInteractResponse(reply=reply, agreed=bool(parsed.get("agreed", False)), relationshipDelta=delta)
