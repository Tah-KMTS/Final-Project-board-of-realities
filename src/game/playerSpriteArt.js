export const PLAYER_ART_FRAME_W = 44;
export const PLAYER_ART_FRAME_H = 80;
// Displayed scale: brings the 80px-tall art down toward the generic NPC
// sprite's 64px height so the player doesn't tower over everything else.
export const PLAYER_ART_SCALE = 0.8;

const ROWS_BY_FACING = { down: DOWN, up: UP, right: RIGHT, left: RIGHT };

function padRow(row, w) {
  return row.length >= w ? row.slice(0, w) : row + '.'.repeat(w - row.length);
}

// Draws one facing/step frame into `ctx` at horizontal offset `ox` (within
// the shared walk-cycle strip canvas spriteGen.js builds). `left` reuses
// the `right` art unmirrored — spriteGen.js flips it via Phaser's
// setFlipX instead of this module authoring separate mirrored pixels.
export function drawPlayerArtFrame(ctx, ox, facing, step) {
  const sourceRows = ROWS_BY_FACING[facing] || DOWN;
  const w = Math.max(...sourceRows.map((r) => r.length));
  const rows = sourceRows.map((r) => padRow(r, w));
  const h = rows.length;
  const xPad = Math.round((PLAYER_ART_FRAME_W - w) / 2);
  const yBob = step === 1 ? 1 : 0; // subtle 1px walk bounce on the alternate step frame

  const get = (x, y) => (x < 0 || x >= w || y < 0 || y >= h ? '.' : rows[y][x]);
  const group = (x, y) => GROUP[get(x, y)] || 'bg';

  for (let y = 0; y < h; y++) {
    const dy = y + yBob;
    if (dy >= PLAYER_ART_FRAME_H) continue;
    for (let x = 0; x < w; x++) {
      const ch = get(x, y);
      const g = group(x, y);
      let color = LEGEND[ch] ?? null;
      if (!NO_ERODE.has(g)) {
        const neighbors = [group(x - 1, y), group(x + 1, y), group(x, y - 1), group(x, y + 1)];
        if (neighbors.some((n) => n !== g)) color = OUTLINE_COLOR;
      }
      if (color === null) continue; // stays transparent
      ctx.fillStyle = color;
      ctx.fillRect(ox + xPad + x, dy, 1, 1);
    }
  }
}
