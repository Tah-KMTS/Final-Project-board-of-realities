// Key-value map for fast lookup by member ID
export const SYNDICATE_MEMBERS_BY_ID = SYNDICATE_MEMBERS.reduce((acc, member) => {
  acc[member.id] = member
  return acc
}, {})

/**
 * Returns full detailed profile object for a given syndicate member ID.
 */
export function getSyndicateMember(memberId) {
  return SYNDICATE_MEMBERS_BY_ID[memberId] || null
}

/**
 * Returns the schedule details for a given syndicate member at a specific time block index (0 to 4)
 * or time block name.
 */
export function getSyndicateMemberSchedule(memberId, timeBlockKey) {
  const member = getSyndicateMember(memberId)
  if (!member || !member.dailySchedule) return null

  const keys = ['morning', 'midday', 'afternoon', 'night', 'midnight']
  let key = 'morning'

  if (typeof timeBlockKey === 'number') {
    key = keys[timeBlockKey % keys.length]
  } else if (typeof timeBlockKey === 'string') {
    const lower = timeBlockKey.toLowerCase()
    if (lower.includes('morning') || lower.includes('8:00 am')) key = 'morning'
    else if (lower.includes('midday') || lower.includes('12:00 pm')) key = 'midday'
    else if (lower.includes('afternoon') || lower.includes('4:00 pm')) key = 'afternoon'
    else if (lower.includes('night') && !lower.includes('midnight') || lower.includes('8:00 pm')) key = 'night'
    else if (lower.includes('midnight') || lower.includes('12:00 am')) key = 'midnight'
  }

  return member.dailySchedule[key] || member.dailySchedule.morning
}

/**
 * Get all members belonging to a specific syndicate ID.
 */
export function getSyndicateRoster(syndicateId) {
  return SYNDICATE_MEMBERS.filter((m) => m.syndicateId === syndicateId)
}
